"""Generate the native action/progress wire models from Zook's canonical schema."""
import argparse
from pathlib import Path
import re
import yaml

ROOT=Path(__file__).resolve().parents[1]
NAMES=['LightTickActionTarget','LightTickActionProgress','LightTickActionCapabilities','LightTickPracticeSource','LightTickPracticeOrigin','LightTickPracticeFeedback','LightTickActionPlan',
       'LightTickActionExecution','LightTickActionWorkspace','LightTickLearningStageProgress',
       'LightTickLearningPlanProgress','LightTickLearningProgress','LightTickLearningProgressData','LightTickLearningLessonSummary','LightTickLearningLesson','LightTickLearningLibraryData','LightTickLearningLessonData','LightTickLearningAnswer','LightTickLearningPrivateState','LightTickLearningPrivateOperation','LightTickLearningPrivateData','LightTickLearningPrivateCommand']


def wire_type(value,language):
    nullable=False
    if 'anyOf' in value:
        nullable=any(v.get('type')=='null' for v in value['anyOf'])
        value=next(v for v in value['anyOf'] if v.get('type')!='null')
    kind=value.get('type')
    if isinstance(kind,list):nullable='null' in kind;kind=next(v for v in kind if v!='null')
    if '$ref' in value:result=value['$ref'].rsplit('/',1)[1]
    elif kind=='array':
        item=wire_type(value['items'],language)[0]
        result=f'[{item}]' if language=='swift' else f'List<{item}>'
    elif kind=='string' or 'enum' in value and all(isinstance(v,str) for v in value['enum']):result='String'
    elif kind=='integer' or type(value.get('const')) is int:result='Int'
    elif kind=='boolean' or type(value.get('const')) is bool:result='Bool' if language=='swift' else 'Boolean'
    else:raise ValueError(f'Unsupported public wire model property: {value}')
    return result,nullable


def generate(schemas,language):
    lines=['// Shared action workspace. Generated by build_scripts/generate_action_clients.py.']
    for name in NAMES:
        schema=schemas[name];required=set(schema.get('required',[]))
        fields=[]
        for key,value in schema['properties'].items():
            # Optional open-ended link metadata is intentionally not interpreted
            # by native clients. It cannot become a client-controlled URL.
            if key=='linked_source':continue
            kind,nullable=wire_type(value,language);optional=nullable or key not in required
            fields.append((key,kind+('?' if optional else ''),optional))
        if language=='swift':
            protocols='Codable, Equatable, Sendable'+(', Identifiable' if 'id' in schema['properties'] else '')
            lines.append(f'public struct {name}: {protocols} {{')
            lines.extend(f'    public var {key}: {kind}' for key,kind,_ in fields)
            lines.append('}')
        else:
            lines.append(f'data class {name}(')
            lines.extend(f'    val {key}: {kind}'+(' = null' if optional else '')+',' for key,kind,optional in fields)
            lines.append(')')
    return '\n'.join(lines)+'\n\n'


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    schemas=yaml.safe_load((ROOT/'api-contracts/openapi/lighttick/api.yaml').read_text())['components']['schemas']
    for language,path in [('swift','api-contracts/clients/lighttick/swift/Sources/LightTickContracts/LightTickContracts.swift'),
                          ('kotlin','api-contracts/clients/lighttick/kotlin/src/main/kotlin/lighttick/contracts/LightTickContracts.kt')]:
        p=ROOT/path;source=p.read_text();pattern=r'// Shared action workspace\..*?(?=// Independent)'
        output,count=re.subn(pattern,lambda _:generate(schemas,language),source,flags=re.S)
        if count!=1:raise ValueError('Expected exactly one shared action wire-model section')
        if args.check:
            if output!=source:raise SystemExit(f'Native action contracts are stale: {path}')
        else:p.write_text(output)


if __name__=='__main__':main()
