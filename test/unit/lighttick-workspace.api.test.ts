import assert from "node:assert/strict";
import test from "node:test";
import { Ajv2020 } from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import * as contracts from "../../src/generated/openapi/public-contracts.generated.ts";
import { ApplicationError } from "../../src/shared/errors.ts";
import { createApplication } from "../support/create-test-application.ts";
import { buildDefaultSeed } from "../../src/infrastructure/database/prisma/default-seed.ts";
import { InMemoryLightTickRepository } from "../../src/testing/in-memory-lighttick-repository.ts";

test("workspace routes: real envelopes, ownership, CAS, receipt replay and core restrictions", async () => {
  const ajv = new Ajv2020({strict:false}); addFormats(ajv);
  const check = (name: string, value: unknown) => { const validate = ajv.compile((contracts as any)[name+"Schema"]); assert.equal(validate(JSON.parse(JSON.stringify(value))),true,JSON.stringify(validate.errors)); };
  const seed = buildDefaultSeed(undefined, { includeLightTick: true });
  for (const userId of ["user_alice", "user_bob"]) seed.appUsers.push({ id: "workspace-" + userId, appId: "lighttick", userId, status: "ACTIVE", accountRegion: "UNKNOWN", joinedAt: new Date().toISOString() });
  const repo = new InMemoryLightTickRepository();
  const app = await createApplication({ seed, lighttickEnabled: true, lighttickRepository: repo });
  app.services.lighttickRuntime.nativeLearning.enabled = true;
  const credentials = { repository: "owner/repo", branch: "main", token: "synthetic-secret" };
  app.services.lighttickRuntime.github = { summary: async () => ({ mode: "custom", configured: true, revision: 1 }), credentials: async () => credentials, assertCurrent: async () => {} } as any;
  const call = (method: string, path: string, body?: unknown, key = "workspace-test-key", user = "user_alice") => app.app.handle({ method, path: "/api/v1/lighttick/" + path, body, headers: {
    authorization: "Bearer " + app.services.tokenService.issueAccessToken(user, "lighttick"), "x-app-id": "lighttick", "x-lighttick-task-schema":"2", "idempotency-key": key } } as any);
  const billing = await call("GET", "billing/subscription");
  check("LightTickWorkspaceBillingEnvelope",billing.body);
  assert.equal(billing.body.data.purchase_available, false);
  assert.equal((await call("POST", "billing/upgrade", { planId: "premium" })).statusCode, 503);
  const body = { type: "github", prefix: "courses", base_revision: 0 };
  const created = await call("POST", "storage", body);
  assert.equal(created.statusCode, 200, JSON.stringify(created.body));
  check("LightTickWorkspaceStorageEnvelope",created.body);
  const storage = created.body.data.storage;
  assert.ok(storage.id);
  assert.equal(JSON.stringify(created.body).includes("synthetic-secret"), false);
  assert.deepEqual((await call("POST", "storage", body)).body.data, created.body.data);
  assert.equal((await call("POST", "storage", { ...body, prefix: "different" })).statusCode, 409);
  assert.equal((await call("POST", "storage", body, "workspace-stale-key")).statusCode, 409);
  assert.equal((await call("GET", "storage", undefined, undefined, "user_bob")).body.data.storage.length, 0);
  assert.equal((await call("GET", "storage/" + storage.id, undefined, undefined, "user_bob")).statusCode, 404);
  assert.equal((await call("POST", "storage", { ...body, prefix: "../secret" }, "workspace-bad-path")).statusCode, 422);
  const connected = await call("PUT", "learning/modules/english-reading/source", { title: "English", storage_id: storage.id, base_revision: 0 }, "workspace-source-key");
  assert.equal(connected.statusCode, 200, JSON.stringify(connected.body));
  assert.equal((await call("GET", "learning/modules/english-reading/sync-status")).body.data.module.revision, 1);
  const native = app.services.lighttickRuntime.nativeLearning;
  const before = await repo.getLearningModule({ appId: "lighttick", userId: "user_alice" }, "english-reading");
  await assert.rejects(native.command({appId:"lighttick",userId:"user_alice"},"workspace-rollback-key","module:sync","english-reading",{},async () => {
    await repo.saveLearningModule({ ...before!, revision: 2 }, 1); throw Error("synthetic database failure");
  }));
  assert.equal((await repo.getLearningModule({appId:"lighttick",userId:"user_alice"},"english-reading"))?.revision, 1);
  const goal = (await call("POST", "goals", {title:"Exact task lookup"},"workspace-goal-key")).body.data;
  const date = (await call("GET","today")).body.data.business_date;
  const plan = (await call("POST","manual-plans",{goal_id:goal.id,title:"Task lookup plan",completion_criteria:"",period_start:date,period_end:date,tasks:[{id:"workspace-task-item",title:"Exact search task",scheduled_for:date,estimated_minutes:null,completion_criteria:"",guidance:""}]},"workspace-plan-key")).body.data;
  const confirmed = (await call("POST",`manual-plans/${plan.id}/confirm`,{base_version:plan.version,goal_base_version:plan.goal_version},"workspace-confirm-key")).body.data;
  const task = confirmed.tasks[0];
  const detail = await call("GET",`tasks/${task.id}`);
  assert.equal(detail.statusCode,200,JSON.stringify(detail.body));
  assert.equal(detail.body.data.title,"Exact search task");
  check("LightTickTaskData",detail.body.data);
  assert.equal((await call("GET",`tasks/${task.id}`,undefined,undefined,"user_bob")).statusCode,404);
  assert.equal((await call("GET","tasks/unknown-task")).statusCode,404);
  app.services.lighttickRuntime.scopePolicy.assertFull = async () => { throw new ApplicationError(503,"LIGHTTICK_CAPABILITY_UNAVAILABLE","core"); };
  assert.equal((await call("GET", "storage")).statusCode, 200);
  assert.equal((await call("POST", "storage", body, "workspace-core-key")).statusCode, 503);
});
