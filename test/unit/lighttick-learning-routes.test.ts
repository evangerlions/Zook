import assert from "node:assert/strict";
import test from "node:test";
import { NativeLearningService } from "../../src/modules/lighttick/learning/native-learning.service.ts";
import { LearningRouteService } from "../../src/modules/lighttick/learning/learning-route.service.ts";
import { routeProgress, compatibleRouteProgress } from "../../src/modules/lighttick/learning/learning-route.progress.ts";
import { InMemoryLightTickRepository } from "../../src/testing/in-memory-lighttick-repository.ts";
import { routeFixture } from "../support/learning-route-fixture.ts";
const owner={appId:"lighttick" as const,userId:"synthetic-route-owner"},id="plan-synthetic-course";
async function setup() {
  const repo=new InMemoryLightTickRepository(), native=new NativeLearningService(repo,true), routes=new LearningRouteService(native), f=routeFixture();
  await routes.save(owner,id,{base_revision:0,...f},"route-create-original");
  await routes.publish(owner,id,{base_revision:1},"route-publish-original");
  return {repo,native,routes,f};
}
test("formal route publishes immutable versions, stable sequential lessons, and explicit per-version stage progress",async()=>{
  const {repo,native,routes,f}=await setup();
  const body={base_revision:2,lesson_id:"lesson-route-first",base_lesson_revision:0,content:"Original teaching",references:"Reviewed reference",source_url:""};
  const first=await routes.publishLesson(owner,id,1,body,"route-lesson-original");
  assert.deepEqual(await routes.publishLesson(owner,id,1,body,"route-lesson-original"),first);
  assert.equal((await routeProgress(native,owner,id)).percent,0);
  await native.privateCommand(owner,first.id,{content_version:first.content_version,action:"position",base_revision:0,position:999},"route-position-original");
  assert.equal((await routeProgress(native,owner,id)).completed_lessons,0);
  const revision=(await native.authority(owner))!.revision;
  await native.privateCommand(owner,first.id,{content_version:first.content_version,action:"complete",base_revision:0},"route-completion-original");
  const progress=await routeProgress(native,owner,id);
  assert.equal(progress.percent,50);assert.equal(progress.stages[0].percent,100);assert.equal(progress.stages[1].percent,0);
  assert.ok((await native.authority(owner))!.revision>revision);
  const before=await compatibleRouteProgress(native,owner,"https://grow.example/grow/");assert.equal(before?.plans[0].completed_lessons,1);
  await assert.rejects(native.publish(owner,first.id,{base_revision:1,collection_id:id,number:1,title:"Bypass",content:"Bypass",references:""},"route-bypass-original"),{statusCode:409});
  const revised=await routes.publishLesson(owner,id,1,{...body,base_revision:3,base_lesson_revision:1,content:"Revised teaching"},"route-lesson-revised");
  assert.equal((await routeProgress(native,owner,id)).completed_lessons,0);
  assert.equal((await native.privateState(owner,first.id,first.content_version)).completed,true);
  assert.equal((await native.privateState(owner,first.id,revised.content_version)).completed,false);
  await routes.save(owner,id,{base_revision:4,...f,brief:{...f.brief,title:"Renamed route draft"}},"route-edit-original");
  assert.equal((await routeProgress(native,owner,id)).name,f.brief.title,"draft edits are not published progress");
  await routes.publish(owner,id,{base_revision:5},"route-second-version");
  assert.equal((await routes.read(owner,id,1)).brief.title,f.brief.title);
  assert.equal((await routeProgress(native,owner,id)).name,"Renamed route draft");
  await routes.save(owner,id,{base_revision:6,...f,document:{...f.document,lessons:f.document.lessons.map((l,n)=>n?l:{...l,goal:"Rewritten published blueprint"})}},"route-edit-blueprint");
  await assert.rejects(routes.publish(owner,id,{base_revision:7},"route-rewrite-published"),{statusCode:409});
  assert.equal((await routes.read(owner,id,2)).document.lessons[0].goal,f.document.lessons[0].goal);
  await repo.deleteOwnerData(owner);assert.equal(await repo.learningRoutes.getLearningRoute(owner,id),undefined);
});
test("route owner, CAS, permissions, cursor scope and archived receipts stay enforced",async()=>{
  const {repo,native,routes,f}=await setup();
  await routes.save(owner,"plan-synthetic-second",{base_revision:0,...f},"route-second-create");
  const page=await routes.list(owner,"",1);assert.ok(page.next_cursor);
  await assert.rejects(routes.list({...owner,userId:"other-owner"},page.next_cursor!,1),{statusCode:400});
  await assert.rejects(routes.save(owner,id,{base_revision:1,...f},"route-stale-cas"),{statusCode:409});
  await routes.transition(owner,id,{base_revision:2,status:"paused"},"route-pause-original");
  await assert.rejects(routes.list(owner,page.next_cursor!,1),{statusCode:409});
  await assert.rejects(routes.publishLesson(owner,id,1,{base_revision:3,lesson_id:"lesson-route-paused",base_lesson_revision:0,content:"Paused"},"route-paused-write"),{statusCode:409});
  await routes.transition(owner,id,{base_revision:3,status:"active"},"route-resume-original");
  const archived=await routes.transition(owner,id,{base_revision:4,status:"archived"},"route-archive-original");
  assert.deepEqual(await routes.transition(owner,id,{base_revision:4,status:"archived"},"route-archive-original"),archived);
  const authority=(await native.authority(owner))!;
  await native.consent(owner,{base_revision:authority.revision,reading_enabled:false,private_enabled:false},"route-withdraw-reading");
  await assert.rejects(routes.read(owner,id),{statusCode:403});
  await assert.rejects(routes.publish(owner,id,{base_revision:1},"route-publish-original"),{statusCode:403},"accepted replay cannot expose withdrawn content");
  assert.equal((await repo.learningRoutes.listLearningRoutes(owner,"",100)).length,2);
});
