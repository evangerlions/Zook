test("late cancellation, changed account and expired lease fence publication and retain queued originals", async () => {
    const f = await fixture(), b = { kind: "valuation", base_revision: 1, date: "2026-10-26", sources: {} };
    const w = await f.s.create(f.o, f.id, b, "portfolio-cancel-preview");
    let release!: () => void, started!: () => void;
    const ready = new Promise<void>(r => { started = r; });
    const runner = new PortfolioRunner(f.s, async () => { }, async (c, b) => { started(); await new Promise<void>(r => { release = r; }); return calculatePortfolio(c, b); });
    const run = runner.execute(f.o, w.id);
    await ready;
    const live = await f.s.readWork(f.o, f.id, w.id);
    await f.s.cancel(f.o, f.id, w.id, { base_revision: live.revision }, "portfolio-cancel-original");
    release();
    await run;
    assert.equal((await f.s.readWork(f.o, f.id, w.id)).status, "cancelled");
    assert.equal((await f.s.valuations(f.o, f.id)).items.length, 0);
    const next = await f.s.create(f.o, f.id, b, "portfolio-changed-preview");
    await f.append(f.cash("3"));
    await f.pr.execute(f.o, next.id);
    assert.equal((await f.s.readWork(f.o, f.id, next.id)).status, "failed");
});
test("related-day correction stales immutable history and cursor while later-date facts do not; original adoption survives stale CAS", async () => {
    const f = await fixture();
    const first = await f.append(f.cash("1"));
    const a = await f.repo.investments.account(f.o, f.id);
    const b = { kind: "valuation", base_revision: a!.revision, date: "2026-11-01", sources: {} };
    const w = await f.s.create(f.o, f.id, b, "portfolio-history-preview");
    await f.pr.execute(f.o, w.id);
    const p = await f.s.readWork(f.o, f.id, w.id), adopt = { base_revision: a!.revision, preview_digest: (p.output as any).preview_digest };
    const saved = await f.s.adopt(f.o, f.id, w.id, adopt, "portfolio-history-adopt");
    const second = await f.s.create(f.o, f.id, b, "portfolio-history-second");
    await f.pr.execute(f.o, second.id);
    const p2 = await f.s.readWork(f.o, f.id, second.id);
    await f.s.adopt(f.o, f.id, second.id, { ...adopt, preview_digest: (p2.output as any).preview_digest }, "portfolio-history-second-adopt");
    const page = await f.s.valuations(f.o, f.id, "", 1) as any;
    assert.ok(page.next_cursor);
    const correction = await f.l.append(f.o, f.id, await f.body(first.id, f.cash("2")), "portfolio-historical-correction");
    await f.runner.execute(f.o, correction.id);
    const values = await f.s.valuations(f.o, f.id) as any;
    assert.equal(values.items.every((v: any) => v.stale), true);
    assert.deepEqual(values.items.find((v: any) => v.id === saved.id).output, saved.output);
    await assert.rejects(() => f.s.valuations(f.o, f.id, page.next_cursor, 1), /cursor expired/);
    assert.equal((await f.s.adopt(f.o, f.id, w.id, adopt, "portfolio-history-adopt")).id, saved.id);
});
