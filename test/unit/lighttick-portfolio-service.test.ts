test("valuation preview requires explicit adoption, original body survives response loss and later-date events keep history current", async () => {
    const f = await fixture(), body = { kind: "valuation", base_revision: 1, date: "2026-10-26", sources: {} };
    const w = await f.s.create(f.o, f.id, body, "portfolio-original-preview");
    assert.equal((await f.s.valuations(f.o, f.id)).items.length, 0);
    await f.pr.execute(f.o, w.id);
    const preview = await f.s.readWork(f.o, f.id, w.id);
    assert.equal(preview.status, "succeeded");
    assert.equal((await f.s.create(f.o, f.id, body, "portfolio-original-preview")).id, w.id);
    const adopted = await f.s.adopt(f.o, f.id, w.id, { base_revision: 1, preview_digest: preview.output!.kind !== "performance" && preview.output!.preview_digest }, "portfolio-original-adopt");
    assert.equal(adopted.output.kind === "valuation" && adopted.output.balance.equity, "100");
    await f.append(f.cash("2"));
    assert.equal((await f.s.valuations(f.o, f.id)).items[0].stale, false);
    await assert.rejects(() => f.s.create(f.o, f.id, { ...body, date: "2026-10-27" }, "portfolio-original-preview"));
    await assert.rejects(() => f.s.readWork({ ...f.o, userId: "foreign-owner" }, f.id, w.id));
});
