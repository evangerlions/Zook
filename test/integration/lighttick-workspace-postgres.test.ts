import assert from "node:assert/strict";
import test from "node:test";
import { Pool } from "pg";
import { PostgresLightTickRepository } from "../../src/infrastructure/database/postgres/postgres-lighttick-repository.ts";
import { runPostgresMigrations } from "../../src/infrastructure/database/postgres/migrate.ts";
import { NativeLearningService } from "../../src/modules/lighttick/learning/native-learning.service.ts";
import { LearningContentSyncService } from "../../src/modules/lighttick/learning/content-sync.service.ts";
import { digest } from "../../src/modules/lighttick/learning/native-learning.validation.ts";
import { randomUUID } from "node:crypto";
const dsn = process.env.LIGHTTICK_TEST_DATABASE_URL;
if (!dsn || !new URL(dsn).pathname.startsWith("/grow_web_u1_") || new URL(dsn).hostname !== "127.0.0.1") throw Error("Disposable local test database required");
test("PostgreSQL GitHub import: immutable UTF8 content, repeat, update, archive, rollback and reconnect", async () => {
  await runPostgresMigrations({ connectionString: dsn, log: () => {} });
  const pool = new Pool({ connectionString: dsn });
  const repo = new PostgresLightTickRepository(pool), native = new NativeLearningService(repo, true);
  const owner = { appId: "lighttick" as const, userId: "workspace-pg-" + randomUUID() };
  let commit = "a".repeat(40), docs = { "one.md": "# 中文第一课\n原始正文", "nested/two.md": "# 第二课\n第二课正文" } as Record<string,string>;
  const transport: typeof fetch = async (url) => {
    const path = String(url);
    if (path.includes("git/ref/")) return Response.json({ object: { sha: commit } });
    if (path.includes("git/trees/")) return Response.json({ truncated: false, tree: Object.entries(docs).map(([p, content], index) => ({ path: "courses/"+p, sha: String(index), type: "blob", size: Buffer.byteLength(content) })) });
    const index = Number(path.split("/").at(-1));
    return Response.json({ content: Buffer.from(Object.values(docs)[index]).toString("base64"), encoding: "base64" });
  };
  const credentials = { repository: "owner/repo", branch: "main", token: "synthetic" };
  try {
    await native.authority(owner);
    await repo.saveLearningModule({ ...owner, id: "english-reading", title: "English", description: "", enabled: true, sourceType: "github", sourceUrl: null, sourcePath: "courses", sourceConfig: { github: { ...credentials, token: undefined, prefix: "courses", syncInterval: "manual" } }, revision: 1, createdAt: new Date().toISOString(), updatedAt: new Date().toISOString() }, 0);
    const storageId = randomUUID();
    await repo.saveUserStorage({id:storageId,userId:owner.userId,type:"github",revision:1,github:{...credentials,token:undefined,prefix:"courses"}});
    assert.equal((await repo.getUserStorage(owner,storageId))?.id,storageId);
    assert.equal((await repo.listUserStorage({...owner,userId:"other"})).length,0);
    const sync = (key: string, force = false) => new LearningContentSyncService(repo,transport).sync(owner,"english-reading",force,credentials,fn => native.command(owner,key,"module:sync","english-reading",{force},fn),async () => {});
    const result = await sync("workspace-pg-first");
    assert.equal(result.added,2);
    const lessons = await repo.listNativeLessons(owner,"",100);
    assert.equal(lessons.length,2);
    const first = lessons.find(l => l.title === "中文第一课")!;
    assert.ok(first);
    const version = first.publishedVersion!;
    assert.equal(version,digest({content:docs["one.md"],references:""}));
    assert.equal((await repo.getLessonPublication(owner,first.id,version))?.content,docs["one.md"]);
    await native.privateCommand(owner, first.id, { action:"save", content_version:version, base_revision:0, notes:"私人笔记", answers:[] },"workspace-pg-note");
    assert.equal((await sync("workspace-pg-skipped")).status,"skipped");
    docs = {"one.md":"# 中文第一课\n更新正文"}; commit="b".repeat(40);
    const updated = await sync("workspace-pg-second");
    assert.equal(updated.updated,1); assert.equal(updated.deleted,1);
    assert.equal((await native.privateState(owner,first.id,version)).notes,"私人笔记");
    const moduleBefore = await repo.getLearningModule(owner,"english-reading");
    docs={"three.md":"# 新课\n原子测试"}; commit="c".repeat(40);
    const save = repo.insertLessonPublication;
    repo.insertLessonPublication=async()=>{throw Error("synthetic write failure");};
    await assert.rejects(sync("workspace-pg-rollback"),/synthetic write failure/);
    repo.insertLessonPublication=save;
    assert.equal((await repo.getLearningModule(owner,"english-reading"))?.revision,moduleBefore?.revision);
    assert.equal(await repo.getOperation(owner,"learning:workspace-pg-rollback"),undefined);
    assert.equal((await sync("workspace-pg-rollback")).added,1);
    const reconnected=new PostgresLightTickRepository(pool);
    assert.equal((await reconnected.getNativePrivateState(owner,first.id,version))?.notes,"私人笔记");
    assert.ok((await reconnected.getStorageUsage(owner)).totalUsed > 0);
    await reconnected.deleteOwnerData(owner);
    assert.equal((await reconnected.listUserStorage(owner)).length,0);
  } finally { await repo.deleteOwnerData(owner); await pool.end(); }
});
